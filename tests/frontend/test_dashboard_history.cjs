const assert = require('node:assert/strict');
const path = require('node:path');
const {api, setWorkspaceId} = require(path.resolve(process.argv[2], 'api.js'));
const originalFetch = global.fetch;
const respond = value => new Response(JSON.stringify(value));
const run = i => ({id:`run-${i}`, plan_id:i%2?'plan-a':'plan-b'});
(async()=>{
  setWorkspaceId('team-history');
  const calls=[];
  global.fetch=async(url,init)=>{
    calls.push(url);
    assert.equal(init.headers.get('X-Workspace-Id'),'team-history');
    const params=new URL(url,'http://fixture').searchParams;
    const page=Number(params.get('page'));const size=Number(params.get('page_size'));
    assert.equal(size,100);
    return respond({items:Array.from({length:Math.min(size,450-(page-1)*size)},(_,i)=>run((page-1)*size+i)),total:450,page,page_size:size});
  };
  const result=await api.dashboardRuns(new AbortController().signal);
  assert.equal(result.length,450,'Loads all pages beyond the legacy 30 and 200 limits');
  assert.equal(result.filter(r=>r.plan_id==='plan-a').length,225);
  assert.equal(calls.length,5);
  global.fetch=async()=>respond({items:[],total:0,page:1,page_size:100});
  assert.deepEqual(await api.dashboardRuns(new AbortController().signal),[]);
  let pageCalls=0;
  global.fetch=async()=>++pageCalls===1?respond({items:[run(1)],total:101,page:1,page_size:100}):new Response('Unavailable',{status:503});
  await assert.rejects(api.dashboardRuns(new AbortController().signal),/Unavailable/,'Never returns partial history after a later page fails');
  const controller=new AbortController();pageCalls=0;
  global.fetch=async()=>{pageCalls++;controller.abort();return respond({items:[run(1)],total:101,page:1,page_size:100});};
  await assert.rejects(api.dashboardRuns(controller.signal),{name:'AbortError'});
  assert.equal(pageCalls,1);
  pageCalls=0;setWorkspaceId('old-workspace');
  global.fetch=async()=>{pageCalls++;setWorkspaceId('new-workspace');return respond({items:[run(1)],total:101,page:1,page_size:100});};
  await assert.rejects(api.dashboardRuns(new AbortController().signal),{name:'AbortError'});
  assert.equal(pageCalls,1,'Does not fetch the next page in another workspace');
  setWorkspaceId('team-history');pageCalls=0;
  global.fetch=async()=>{pageCalls++;return respond({items:[run(1),run(pageCalls+1)],total:101,page:pageCalls,page_size:100});};
  assert.equal((await api.dashboardRuns(new AbortController().signal)).length,3,'Deduplicates repeated IDs across pages');
  console.log('Dashboard history pagination, failure, cancellation, workspace and deduplication checks passed');
})().catch(error=>{console.error(error);process.exitCode=1;}).finally(()=>{global.fetch=originalFetch;setWorkspaceId(null);});
